// Paseo bundles TypeScript but does not copy arbitrary source assets.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const source = await readFile(new URL('../server/observer-source.mjs', import.meta.url), 'utf8');
const version = createHash('sha256').update(source).digest('hex');
const output = '// Generated by scripts/build-observer.mjs; do not edit.\n' +
  'export const observerAsset = ' + JSON.stringify({ version, source }) + ' as const;\n';
const path = new URL('../server/observer-assets.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8').catch(() => null) !== output)
    throw new Error('Observer bundle is stale; run npm run build:observer');
} else await writeFile(path, output);
